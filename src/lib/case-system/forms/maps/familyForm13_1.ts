/** Which side the person is on, when the record says: true for the side they are on, false for the other; null if not held. */
const filedBy = (side: "applicant" | "respondent") => (ctx: FormContext): boolean | null => {
  if (ctx.file.side.state !== "answered") return null;
  return (side === "applicant") === bringsTheCase(ctx.file);
};

