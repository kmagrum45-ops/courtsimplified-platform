/**
 * The glossary (rebuilt 2026-10-13).
 *
 * WHY IT CHANGED. The first glossary (2026-09-30) was made only from the
 * definitions provisions of the rules and statutes, and explained each word
 * only from those provisions. The Family Law Rules have by far the longest
 * definitions list, so most entries read "In the family rules, ..." even for
 * words every court uses (bond, case, clerk, address), environmental terms
 * from the Limitations Act appeared beside them, and words people actually
 * meet in court ("affidavit", "noted in default", "costs") were missing
 * because no definitions provision defines them.
 *
 * NOW. glossaryEntries.json is hand-written. Each entry says first what the
 * word means wherever it is used, then (only where the courts differ) what it
 * means in Small Claims Court, the civil courts or family court. Every
 * statement rests on the sources listed with it, each carrying a quote that
 * test:glossary finds word for word in the saved copy of that source
 * (docs/sources/corpus). The law's own definitions (glossaryIndex.json,
 * generated by scripts/glossary/buildGlossary.ts) are still shown underneath,
 * matched by term. A defined term not worth a self-represented person's time
 * is listed in `removed` with the reason, so nothing disappears silently.
 *
 * Latin: Ontario's rules and statutes use English ("without notice", not
 * ex parte) and define no Latin. Only phrases still heard in court, and that a
 * court publishes a meaning for, are included (kind "latin").
 */
import index from "./glossaryIndex.json";
import authored from "./glossaryEntries.json";

export type GlossaryDefinition = {
  source: string;
  citation: string;
  pinpoint: string;
  url: string;
  definition: string;
};

export type CourtKey = "small-claims" | "civil" | "family";

export const COURT_LABELS: Record<CourtKey, string> = {
  "small-claims": "In Small Claims Court",
  civil: "In civil cases in the Superior Court",
  family: "In family court",
};

export type GlossarySource = {
  /** Corpus id: docs/sources/corpus/<id>.txt */
  id: string;
  title: string;
  citation: string;
  pinpoint: string;
  url: string;
  /** Verbatim (whitespace collapsed) in the saved copy. */
  quote: string;
};

export type AuthoredEntry = {
  term: string;
  kind: "term" | "latin";
  also?: string[];
  meaning: string;
  courts?: Partial<Record<CourtKey, string>>;
  /** Terms in glossaryIndex.json whose definitions belong under this entry, when named differently. */
  lawTerms?: string[];
  /** title, citation and url are filled from the corpus manifest by scripts/glossary/fillSources.ts; test:glossary re-checks them. */
  sources: GlossarySource[];
};

export type GlossaryEntry = {
  id: string;
  term: string;
  kind: "term" | "latin";
  also: string[];
  meaning: string;
  courts: { court: CourtKey; label: string; text: string }[];
  definitions: GlossaryDefinition[];
  sources: GlossarySource[];
  verifiedAt: string;
};

export type GlossaryFile = {
  verifiedAt: string;
  entries: AuthoredEntry[];
  removed: Record<string, string>;
};

const INDEX = index as { generatedAt: string; terms: { term: string; definitions: GlossaryDefinition[] }[] };
export const GLOSSARY_FILE = authored as GlossaryFile;

export function glossaryId(term: string): string {
  return `glossary:${term.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`;
}

const COURT_ORDER: CourtKey[] = ["small-claims", "civil", "family"];

function lawDefinitions(entry: AuthoredEntry): GlossaryDefinition[] {
  const wanted = new Set([entry.term, ...(entry.lawTerms ?? [])].map((term) => term.toLowerCase()));
  return INDEX.terms.filter((indexed) => wanted.has(indexed.term.toLowerCase())).flatMap((indexed) => indexed.definitions);
}

export const GLOSSARY: GlossaryEntry[] = GLOSSARY_FILE.entries
  .map((entry) => ({
    id: glossaryId(entry.term),
    term: entry.term,
    kind: entry.kind,
    also: entry.also ?? [],
    meaning: entry.meaning,
    courts: COURT_ORDER.filter((court) => entry.courts?.[court]).map((court) => ({
      court,
      label: COURT_LABELS[court],
      text: entry.courts![court]!,
    })),
    definitions: lawDefinitions(entry),
    sources: entry.sources,
    verifiedAt: GLOSSARY_FILE.verifiedAt,
  }))
  .sort((a, b) => a.term.localeCompare(b.term, "en", { sensitivity: "base" }));
